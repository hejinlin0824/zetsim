"""事件总线：引擎与前端/器件解耦的唯一通道。"""
from __future__ import annotations
from dataclasses import dataclass
import json
from typing import Callable

@dataclass
class Event:
    t_ns: int
    topic: str
    data: object

class EventBus:
    """Timestamped simulation events for UI, CLI, regression tests and VCD export."""
    def __init__(self):
        self._subs: dict[str, list[Callable]] = {}
        self.log: list[Event] = []
        self.max_log = 200_000

    def subscribe(self, topic: str, fn: Callable):
        self._subs.setdefault(topic, []).append(fn)

    def publish(self, t_ns: int, topic: str, data=None):
        event = Event(int(t_ns), str(topic), data)
        if self.max_log > 0:
            self.log.append(event)
            overflow = len(self.log) - self.max_log
            if overflow > 0:
                del self.log[:overflow]
        for fn in self._subs.get(event.topic, ()):
            fn(event)
        for fn in self._subs.get("*", ()):
            fn(event)

    def query(self, topic: str) -> list[Event]:
        return [event for event in self.log if event.topic == topic]

    def snapshot(self, *, since_ns: int = 0, topics: set[str] | None = None, limit: int | None = None) -> list[Event]:
        events = [event for event in self.log if event.t_ns >= since_ns and (topics is None or event.topic in topics)]
        return events[-limit:] if limit is not None and limit >= 0 else events

    @staticmethod
    def _json_safe(value):
        if isinstance(value, bytes):
            return value.decode("utf-8", "replace")
        if value is None or isinstance(value, (str, int, float, bool)):
            return value
        if isinstance(value, (list, tuple)):
            return [EventBus._json_safe(item) for item in value]
        if isinstance(value, dict):
            return {str(key): EventBus._json_safe(item) for key, item in value.items()}
        return repr(value)

    def to_jsonl(self, *, since_ns: int = 0, topics: set[str] | None = None) -> str:
        lines = [json.dumps({"t_ns": e.t_ns, "topic": e.topic, "data": self._json_safe(e.data)}, ensure_ascii=False, separators=(",", ":"))
                 for e in self.snapshot(since_ns=since_ns, topics=topics)]
        return "\n".join(lines) + ("\n" if lines else "")

    def to_vcd(self, *, topics: set[str] | None = None) -> str:
        """Export scalar GPIO/logic events as VCD; non-scalar topics are omitted."""
        values = {}
        for event in self.snapshot(topics=topics):
            if not (event.topic.startswith("gpio.") or event.topic.startswith("logic.")):
                continue
            if isinstance(event.data, bool):
                bit = int(event.data)
            elif isinstance(event.data, int) and event.data in (0, 1):
                bit = event.data
            else:
                continue
            values.setdefault(event.topic, []).append((event.t_ns, bit))
        names = sorted(values)
        if not names:
            return ""
        ids = {name: "v" + str(i) for i, name in enumerate(names)}
        lines = ["$date generated by zetsim $end", "$version zetsim EventBus $end", "$timescale 1ns $end", "$scope module zetsim $end"]
        lines.extend(f"$var wire 1 {ids[name]} {name.replace('.', '_')} $end" for name in names)
        lines.extend(["$upscope $end", "$enddefinitions $end"])
        timeline = sorted((t, name, bit) for name, samples in values.items() for t, bit in samples)
        last_t = None
        for t, name, bit in timeline:
            if t != last_t:
                lines.append("#" + str(max(0, int(t))))
                last_t = t
            lines.append(str(bit) + ids[name])
        return "\n".join(lines) + "\n"

    def clear(self):
        self.log.clear()
